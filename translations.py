UI = {"en": _EN, "hi": _HI, "te": _TE}


def t(lang: str, key: str) -> str:
    table = UI.get(lang) or UI["en"]
    value = table.get(key) or UI["en"].get(key)
    if value and value != key and not (
        "_" in value and value.islower() and all(part.isalnum() for part in value.split("_"))
    ):
        return value
    fallback = value or key
    return " ".join(part.capitalize() for part in fallback.replace("_", " ").split() if part)


